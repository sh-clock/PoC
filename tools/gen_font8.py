#!/usr/bin/env python3
"""Generate src/sh_font8.h — an 8x8 1-bit monospace ASCII font for the v9
HUD / mode-browser overlay, rasterized from DejaVu Sans Mono (free font,
bundled with this system). This is PoC debug UI chrome ONLY — it has
NOTHING to do with the engine-verbatim rendering math.

Output: one C array, 95 glyphs (ASCII 32..126), 8 bytes per glyph,
MSB-first (bit 7 = leftmost pixel). Threshold at >= 96.
"""
from PIL import Image, ImageDraw, ImageFont
import sys

TTF = "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf"
OUT = sys.argv[1] if len(sys.argv) > 1 else "src/sh_font8.h"

# Render at a larger size and downsample with a threshold for crisper
# glyphs than a naive 8px render (PIL's own hinting at tiny sizes is poor).
RENDER_SIZE = 32
BOX = 8

font = ImageFont.truetype(TTF, RENDER_SIZE)
glyphs = []

for code in range(32, 127):
    ch = chr(code)
    img = Image.new("L", (RENDER_SIZE * 2, RENDER_SIZE * 2), 0)
    d = ImageDraw.Draw(img)
    d.text((RENDER_SIZE // 2, RENDER_SIZE // 2), ch, font=font, fill=255)
    bbox = img.getbbox()
    if ch == " " or bbox is None:
        glyphs.append([0] * 8)
        continue
    cropped = img.crop(bbox)
    # scale the ink bbox into the 8x8 cell, preserving aspect
    w, h = cropped.size
    scale = min(BOX / w, BOX / h)
    nw, nh = max(1, round(w * scale)), max(1, round(h * scale))
    small = cropped.resize((nw, nh), Image.LANCZOS)
    cell = Image.new("L", (BOX, BOX), 0)
    # center horizontally; sit on the bottom (row 7 = baseline)
    cell.paste(small, ((BOX - nw) // 2, BOX - nh))
    px = cell.load()
    rows = []
    for y in range(BOX):
        b = 0
        for x in range(BOX):
            if px[x, y] >= 96:
                b |= (1 << (7 - x))
        rows.append(b)
    glyphs.append(rows)

with open(OUT, "w") as f:
    f.write("/* sh_font8.h — 8x8 1-bit ASCII font (32..126) for the v9 HUD /\n")
    f.write(" * mode-browser overlay. Generated by tools/gen_font8.py from\n")
    f.write(" * DejaVu Sans Mono (free license). Debug UI chrome ONLY — not\n")
    f.write(" * engine content. 8 bytes/glyph, MSB = leftmost pixel.        */\n")
    f.write("#ifndef SH_FONT8_H\n#define SH_FONT8_H\n\n")
    f.write("#define SH_FONT8_FIRST 32\n#define SH_FONT8_COUNT 95\n\n")
    f.write("static const unsigned char SH_FONT8[95][8] = {\n")
    for i, rows in enumerate(glyphs):
        code = 32 + i
        rep = repr(chr(code)) if code != 92 else "'\\\\'"
        f.write("    { %s }, /* %s */\n" %
                (", ".join("0x%02X" % b for b in rows), rep))
    f.write("};\n\n#endif /* SH_FONT8_H */\n")

# quick legibility self-check: dump a sample line as ASCII art
sample = "SH1 MODES 0123456789 [] {} abcxyz"
line = [""] * 8
for ch in sample:
    g = glyphs[ord(ch) - 32] if 32 <= ord(ch) <= 126 else glyphs[0]
    for y in range(8):
        bits = g[y]
        line[y] += "".join("#" if bits & (1 << (7 - x)) else "." for x in range(8))
print("\n".join(line))
print("wrote", OUT)
